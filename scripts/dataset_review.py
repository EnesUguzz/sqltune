"""Inspect the training and evaluation data before a fine-tune: sizes, databases, gold SQL
health, duplicates and SQL features, per source and split.

Purpose: M1b trains on Spider train + BIRD train. Before spending GPU hours, every gold query
is executed once (errors, timeouts, empty results), duplicates are counted and the SQL mix
of train vs eval is compared, so surprises show up here and not in the results. BIRD train
gold queries that do not run are written to data/bird_train/gold_failures.json, which
load_bird_train() then skips (DataConfig.bird_train_skip_failing_gold).
Flow: loaders -> executor.execute (process pool, gold_timeout_s) -> docs/data/dataset-review.md
+ data/bird_train/gold_failures.json + outputs/dataset_review.json (per-question details).
Params: EXEC_WORKERS, GOLD_TIMEOUT_S, MAX_ROWS below; sources in SETS.
Try: `make dataset-review` (a few minutes; BIRD train has some slow gold queries).
"""

from __future__ import annotations

import json
import multiprocessing
import re
import statistics
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from sqltune.config.models import DataConfig, EvalConfig
from sqltune.data.bird import load_bird
from sqltune.data.bird_train import GOLD_FAILURES_FILE, load_bird_train
from sqltune.data.spider import load_spider
from sqltune.domain import Example
from sqltune.evaluation.executor import execute

EXEC_WORKERS = 12
GOLD_TIMEOUT_S = 120.0
MAX_ROWS = 100_000
OUT_MD = Path("docs/data/dataset-review.md")
OUT_JSON = Path("outputs/dataset_review.json")

FEATURES = {
    "JOIN": r"\bjoin\b",
    "GROUP BY": r"\bgroup\s+by\b",
    "ORDER BY": r"\border\s+by\b",
    "nested SELECT": r"\(\s*select\b",
    "set op (UNION/INTERSECT/EXCEPT)": r"\b(union|intersect|except)\b",
    "CASE / IIF": r"\b(case|iif)\b",
    "CAST": r"\bcast\s*\(",
    "date functions": r"\b(strftime|date|julianday)\s*\(",
    "LIKE": r"\blike\b",
}


def _sets() -> dict[str, list[Example]]:
    cfg = DataConfig()
    return {
        "spider train": load_spider(cfg, "train"),
        "spider dev": load_spider(cfg, "dev"),
        "spider test": load_spider(cfg, "test"),
        "bird train": load_bird_train(
            cfg.model_copy(update={"bird_train_skip_failing_gold": False})
        ),
        "bird_diag": load_bird(cfg.model_copy(update={"bird_split": "diag"})),
        "bird_holdout": load_bird(cfg.model_copy(update={"bird_split": "holdout"})),
    }


def _run(ex: Example) -> tuple[str, str, int, float]:
    cfg = EvalConfig(exec_timeout_s=GOLD_TIMEOUT_S, max_result_rows=MAX_ROWS)
    res = execute(ex.db_path, ex.gold_sql, cfg)
    if not res.ok:
        return ex.id, res.error_type or "exec_error", 0, res.elapsed_ms
    n = len(res.rows or [])
    return ex.id, "ok" if n else "empty", n, res.elapsed_ms


def _pct(n: int, total: int) -> str:
    return f"{n} ({100 * n / max(total, 1):.1f}%)"


def review() -> None:
    sets = _sets()
    everything = [ex for exs in sets.values() for ex in exs]
    ctx = multiprocessing.get_context("spawn")
    with ProcessPoolExecutor(max_workers=EXEC_WORKERS, mp_context=ctx) as pool:
        status = {i: (s, n, ms) for i, s, n, ms in pool.map(_run, everything, chunksize=8)}

    lines = [
        "# Dataset review (M1b, before training)",
        "",
        "Generated by `scripts/dataset_review.py`. Gold SQL executed once per question with a "
        f"{GOLD_TIMEOUT_S:.0f} s timeout and a {MAX_ROWS:,} row cap.",
        "",
        "## Sizes and gold health",
        "",
        "| set | questions | DBs | q/DB min-median-max | evidence | gold ok | empty result "
        "| error | timeout | too many rows | gold p95 ms |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    details: dict[str, dict] = {}
    for name, exs in sets.items():
        n = len(exs)
        per_db = Counter(e.db_id for e in exs)
        sizes = sorted(per_db.values())
        st = Counter(status[e.id][0] for e in exs)
        ms = sorted(status[e.id][2] for e in exs)
        lines.append(
            f"| {name} | {n} | {len(per_db)} | {sizes[0]}-{statistics.median(sizes):.0f}-{sizes[-1]} "
            f"| {_pct(sum(1 for e in exs if e.evidence), n)} | {_pct(st['ok'], n)} "
            f"| {_pct(st['empty'], n)} | {_pct(st['exec_error'], n)} | {_pct(st['timeout'], n)} "
            f"| {_pct(st['too_many_rows'], n)} | {ms[int(0.95 * (n - 1))]:.0f} |"
        )
        details[name] = {
            "status": dict(st),
            "failures": [
                {"id": e.id, "db": e.db_id, "status": status[e.id][0], "sql": e.gold_sql}
                for e in exs
                if status[e.id][0] not in ("ok", "empty")
            ],
        }

    lines += [
        "",
        "## Duplicates",
        "",
        "| set | same (db, question) | same (db, gold SQL) |",
        "|---|---|---|",
    ]
    for name, exs in sets.items():
        q = Counter((e.db_id, e.question.strip().lower()) for e in exs)
        g = Counter((e.db_id, " ".join(e.gold_sql.lower().split())) for e in exs)
        lines.append(
            f"| {name} | {sum(c - 1 for c in q.values() if c > 1)} "
            f"| {sum(c - 1 for c in g.values() if c > 1)} |"
        )

    lines += [
        "",
        "## SQL features (share of gold queries)",
        "",
        "| feature | " + " | ".join(sets) + " |",
        "|---|" + "---|" * len(sets),
    ]
    for feat, pattern in FEATURES.items():
        rx = re.compile(pattern, re.IGNORECASE)
        cells = [
            f"{100 * sum(1 for e in exs if rx.search(e.gold_sql)) / len(exs):.0f}%"
            for exs in sets.values()
        ]
        lines.append(f"| {feat} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "| gold SQL length (chars, median) | "
        + " | ".join(
            f"{statistics.median(len(e.gold_sql) for e in exs):.0f}" for exs in sets.values()
        )
        + " |",
    ]

    lines += ["", "## Database overlap", ""]
    train_dbs = {e.db_id for k in ("spider train", "bird train") for e in sets[k]}
    eval_dbs = {e.db_id for k in sets if "train" not in k for e in sets[k]}
    lines.append(f"Train ∩ eval database names: {sorted(train_dbs & eval_dbs) or 'none'}.")

    bird_fail = [f["id"] for f in details["bird train"]["failures"]]
    failures_path = DataConfig().data_dir / "bird_train" / GOLD_FAILURES_FILE
    failures_path.write_text(json.dumps(bird_fail, indent=0), encoding="utf-8")
    lines += [
        "",
        f"BIRD train gold failures written to `{failures_path}`: {len(bird_fail)} "
        "questions (skipped in training).",
    ]

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(details, indent=1), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    review()
