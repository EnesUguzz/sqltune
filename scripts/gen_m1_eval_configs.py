"""Generate experiments/configs/m1/eval/*.yaml: one file per (model, prompt variant, eval set).

Purpose: The M1a matrix is ~40 runs; writing them by hand invites copy errors (wrong model
name, missing BIRD settings). Each generated file is still a plain, readable config.
Flow: this script -> experiments/configs/m1/eval/<model>__<variant>__<set>.yaml ->
`make m1-eval GROUP=<base3b|adapters|qwen7b|qwen14b>` -> results/<run_name>/.
Params: MODELS / VARIANTS / SETS below.
Try: `uv run python scripts/gen_m1_eval_configs.py && ls experiments/configs/m1/eval`.
"""

from __future__ import annotations

from pathlib import Path

import yaml

OUT = Path("experiments/configs/m1/eval")

SETS = {
    "spider": {"data": {"dataset": "spider", "split": "dev", "subset": "full"}},
    "birddiag": {
        "data": {"dataset": "bird", "bird_split": "diag"},
        "evaluation": {"row_compare": "set", "exec_timeout_s": 30.0},
    },
}
VARIANTS = {
    "zero": {},
    "fewshot3": {"prompt": {"few_shot_k": 3}},
    "rows3": {"prompt": {"sample_rows": 3}},
    "retry": {"inference": {"retry_on_error": True}},
    "rows3retry": {"prompt": {"sample_rows": 3}, "inference": {"retry_on_error": True}},
}
SWEEP = ["lc_f0125", "lc_f025", "lc_f05", "lc_f1", "others", "ep3", "lora16", "seed2", "seed3"]
# group -> (served model name, variants); a group runs against one vLLM server
GROUPS: dict[str, list[tuple[str, list[str]]]] = {
    "base3b": [("base", list(VARIANTS))],
    "adapters": [("m0_qlora", ["zero", "retry"])] + [(name, ["zero"]) for name in SWEEP],
    "qwen7b": [("qwen7b", ["zero", "retry"])],
    "qwen14b": [("qwen14b", ["zero", "retry"])],
}


def merge(*parts: dict) -> dict:
    out: dict = {}
    for part in parts:
        for key, value in part.items():
            out[key] = {**out.get(key, {}), **value} if isinstance(value, dict) else value
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for group, entries in GROUPS.items():
        for model, variants in entries:
            for variant in variants:
                for set_name, set_cfg in SETS.items():
                    name = f"{model}__{variant}__{set_name}"
                    body = merge(
                        {"run": {"experiment_name": "m1a", "run_name": f"m1_{name}"}},
                        {"inference": {"model": model}},
                        set_cfg,
                        VARIANTS[variant],
                    )
                    header = (
                        f"# generated by scripts/gen_m1_eval_configs.py (group {group})\n"
                        f"# model {model} | prompt variant {variant} | eval set {set_name}\n"
                        "extends: ../../base.yaml\n"
                    )
                    text = header + yaml.safe_dump(body, sort_keys=False)
                    (OUT / f"{group}--{name}.yaml").write_text(text, encoding="utf-8")
    print(f"{len(list(OUT.glob('*.yaml')))} configs in {OUT}")


if __name__ == "__main__":
    main()
